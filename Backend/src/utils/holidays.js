/**
 * วันพืชมงคล — นับเป็น Peak ตามปกติ (แม้เป็นวันหยุดราชการ)
 * format: 'YYYY-MM-DD'
 */
const PHEUTSAMON_DAYS = [
  '2025-05-09', // วันพืชมงคล 2568
  '2026-05-11', // วันพืชมงคล 2569 (ประมาณการ)
];

/**
 * ตรวจสอบว่าวันที่กำหนดเป็นวันหยุดราชการหรือไม่
 * (ไม่รวมวันเสาร์-อาทิตย์ ตรวจแยกต่างหาก)
 * @param {Date} date
 * @returns {boolean}
 */
function isPublicHoliday(date) {
  const year = date.getFullYear();
  const dateStr = formatDate(date);
  const holidays = HOLIDAYS_BY_YEAR[year] || [];
  return holidays.includes(dateStr);
}

/**
 * ตรวจสอบว่าวันที่กำหนดเป็นวันพืชมงคลหรือไม่
 * (วันพืชมงคล = Peak แม้จะเป็นวันหยุดราชการ)
 * @param {Date} date
 * @returns {boolean}
 */
function isPheutsaMonDay(date) {
  return PHEUTSAMON_DAYS.includes(formatDate(date));
}

/**
 * Format วันที่เป็น 'YYYY-MM-DD'
 * @param {Date} date
 * @returns {string}
 */
function formatDate(date) {
  const y  = date.getFullYear();
  const m  = String(date.getMonth() + 1).padStart(2, '0');
  const d  = String(date.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

module.exports = { isPublicHoliday, isPheutsaMonDay, formatDate };
